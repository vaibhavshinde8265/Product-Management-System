package com.pms.dao;

import com.pms.model.Product;
import com.pms.util.DBConnection;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;

/** Data Access Object: all SQL for the products table (the CRUD operations). */
public class ProductDAO {

    /** READ: all products for the dashboard table. */
    public List<Product> getAllProducts() throws SQLException {
        String sql = "SELECT pid, pname, pprice, pqty FROM products ORDER BY pid";
        List<Product> list = new ArrayList<>();
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                list.add(mapRow(rs));
            }
        }
        return list;
    }

    /** READ: one product by PID, or null if it does not exist. */
    public Product getProductById(int pid) throws SQLException {
        String sql = "SELECT pid, pname, pprice, pqty FROM products WHERE pid = ?";
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setInt(1, pid);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? mapRow(rs) : null;
            }
        }
    }

    /** CREATE: inserts a product. PID is generated by AUTO_INCREMENT. */
    public boolean addProduct(Product p) throws SQLException {
        String sql = "INSERT INTO products (pname, pprice, pqty) VALUES (?, ?, ?)";
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setString(1, p.getPname());
            ps.setBigDecimal(2, p.getPprice());
            ps.setInt(3, p.getPqty());
            return ps.executeUpdate() == 1;
        }
    }

    /** UPDATE: changes name, price and quantity of the product with this PID. */
    public boolean updateProduct(Product p) throws SQLException {
        String sql = "UPDATE products SET pname = ?, pprice = ?, pqty = ? WHERE pid = ?";
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setString(1, p.getPname());
            ps.setBigDecimal(2, p.getPprice());
            ps.setInt(3, p.getPqty());
            ps.setInt(4, p.getPid());
            return ps.executeUpdate() == 1;
        }
    }

    /** DELETE: removes the product. Returns false if no row had this PID. */
    public boolean deleteProduct(int pid) throws SQLException {
        String sql = "DELETE FROM products WHERE pid = ?";
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setInt(1, pid);
            return ps.executeUpdate() == 1;
        }
    }

    /** Converts the current ResultSet row into a Product object. */
    private Product mapRow(ResultSet rs) throws SQLException {
        return new Product(
                rs.getInt("pid"),
                rs.getString("pname"),
                rs.getBigDecimal("pprice"),
                rs.getInt("pqty"));
    }
}
